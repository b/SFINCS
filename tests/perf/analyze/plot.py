def _plot_metric_per_case(
    df: pd.DataFrame,
    title: str,
    ylabel: str,
    column: str,
    subtitle: str,
    out_path: Path,
    yscale: str = "log",
    transform=None,
) -> None:
    """Per-case 5-subplot grid plotting ``column`` for each (config, grid)."""
    cases = _cases_in(df)
    if not cases:
        return
    nrows, ncols, figsize = _layout(len(cases))
    fig, axes = plt.subplots(nrows, ncols, figsize=figsize, squeeze=False)
    flat = axes.flatten()
    for i, case in enumerate(cases):
        ax = flat[i]
        for config in (CPU_REFERENCE, "gpu_n1", "gpu_n2"):
            for grid, style in (("1x", "-"), ("4x", "--")):
                xs, ys = _series(df, case, grid, config, column)
                if len(xs) == 0:
                    continue
                ys_plot = transform(ys) if transform else ys
                label = f"{CONFIG_LABEL[config]} ({grid})"
                ax.plot(
                    xs, ys_plot,
                    marker="o", linestyle=style,
                    color=CONFIG_COLORS[config],
                    label=label,
                )
        ax.set_xscale("log")
        if yscale == "log":
            ax.set_yscale("log")
        ax.set_xticks([LENGTH_SECONDS[L] for L in LENGTHS])
        ax.set_xticklabels(LENGTHS)
        ax.set_xlabel("simulation length")
        ax.set_ylabel(ylabel)
        ax.set_title(case, fontsize=10)
        ax.grid(True, which="both", alpha=0.3)
        if i == 0:
            ax.legend(loc="best", fontsize=8)
    for j in range(len(cases), nrows * ncols):
        flat[j].axis("off")
    _add_title(fig, title, subtitle)
    _save(fig, out_path)


def plot_wall_vs_length(df: pd.DataFrame, label: str, subtitle: str, out_path: Path) -> None:
    _plot_metric_per_case(
        df,
        title=f"Wall time vs simulation length — {label}",
        ylabel="wall time (s)",
        column="wall",
        subtitle=subtitle,
        out_path=out_path,
        yscale="log",
    )


def plot_per_step_vs_length(df: pd.DataFrame, label: str, subtitle: str, out_path: Path) -> None:
    _plot_metric_per_case(
        df,
        title=f"Per-step unaccounted gap vs simulation length — {label}",
        ylabel="per_step = U(L)/step_count (ms)",
        column="per_step",
        subtitle=subtitle,
        out_path=out_path,
        yscale="linear",
        transform=lambda ys: ys * 1000.0,
    )


def compute_gpu_vs_cpu_speedup(
    df: pd.DataFrame,
    case: str,
    grid: str,
    cpu_config: str = CPU_REFERENCE,
    gpu_config: str = "gpu_n2",
) -> tuple[list[int], np.ndarray]:
    """Return ``(length_seconds, speedup)`` for a (case, grid) cell.

    The speedup is ``cpu_config_wall / gpu_config_wall`` evaluated at
    each shared simulation length. Lengths with no measurement on
    either side are dropped. The CPU denominator defaults to the
    module-level ``CPU_REFERENCE`` so a future host with a different
    SMT geometry only needs to flip one constant.
    """
    xs_cpu, ys_cpu = _series(df, case, grid, cpu_config, "wall")
    xs_gpu, ys_gpu = _series(df, case, grid, gpu_config, "wall")
    if len(xs_cpu) == 0 or len(xs_gpu) == 0:
        return [], np.array([])
    cpu_map = dict(zip(xs_cpu.tolist(), ys_cpu.tolist()))
    gpu_map = dict(zip(xs_gpu.tolist(), ys_gpu.tolist()))
    shared = sorted(set(cpu_map) & set(gpu_map))
    if not shared:
        return [], np.array([])
    speedup = np.array([
        cpu_map[s] / gpu_map[s] if gpu_map[s] > 0 else np.nan
        for s in shared
    ])
    return shared, speedup


def plot_gpu_vs_cpu_speedup(df: pd.DataFrame, label: str, subtitle: str, out_path: Path) -> None:
    """y = ``CPU_REFERENCE``_wall / gpu_n2_wall per case; crossover where line > 1."""
    cases = _cases_in(df)
    if not cases:
        return
    nrows, ncols, figsize = _layout(len(cases))
    fig, axes = plt.subplots(nrows, ncols, figsize=figsize, squeeze=False)
    flat = axes.flatten()
    for i, case in enumerate(cases):
        ax = flat[i]
        for grid, style in (("1x", "-"), ("4x", "--")):
            shared, speedup = compute_gpu_vs_cpu_speedup(df, case, grid)
            if not shared:
                continue
            ax.plot(
                shared, speedup,
                marker="o", linestyle=style,
                color="#000000",
                label=f"{grid} grid",
            )
        ax.axhline(1.0, color="red", linestyle=":", alpha=0.5)
        ax.set_xscale("log")
        ax.set_xticks([LENGTH_SECONDS[L] for L in LENGTHS])
        ax.set_xticklabels(LENGTHS)
        ax.set_xlabel("simulation length")
        ax.set_ylabel(f"speedup ({CPU_REFERENCE} / gpu_n2)")
        ax.set_title(case, fontsize=10)
        ax.grid(True, which="both", alpha=0.3)
        if i == 0:
            ax.legend(loc="best", fontsize=8)
    for j in range(len(cases), nrows * ncols):
        flat[j].axis("off")
    _add_title(fig, f"GPU vs CPU speedup vs simulation length — {label}", subtitle)
    _save(fig, out_path)


def plot_component_breakdown(df: pd.DataFrame, label: str, subtitle: str, out_path: Path) -> None:
    """Stacked-bar named components at 1x gpu_n2 4d per case."""
    cases = _cases_in(df)
    if not cases:
        return
    keys = ("boundaries", "momentum", "continuity", "snapwave", "meteo", "output", "U_L")

    fig, ax = plt.subplots(figsize=(max(8, 1.6 * len(cases)), 5))
    x = np.arange(len(cases))
    bottoms = np.zeros(len(cases))
    for key in keys:
        vals = []
        for case in cases:
            row = df[
                (df["case"] == case)
                & (df["grid"] == "1x")
                & (df["length"] == "4d")
                & (df["config"] == "gpu_n2")
            ]
            if row.empty:
                vals.append(0.0)
                continue
            v = row.iloc[0][key]
            vals.append(0.0 if v != v else float(v))
        vals_arr = np.array(vals)
        ax.bar(
            x, vals_arr, bottom=bottoms,
            label=key,
            color=COMPONENT_COLORS[key],
            edgecolor="white", linewidth=0.5,
        )
        bottoms = bottoms + vals_arr
    ax.set_xticks(x)
    ax.set_xticklabels([c.replace("case_prod_", "") for c in cases], rotation=20, ha="right")
    ax.set_ylabel("time (s)")
    ax.set_title("Named-component breakdown at 1x gpu_n2 4d", fontsize=10)
    ax.legend(loc="best", fontsize=8)
    ax.grid(True, axis="y", alpha=0.3)
    _add_title(fig, f"Component breakdown — {label}", subtitle)
    _save(fig, out_path)


