DEFAULT_CASE_ORDER = (
    "case_prod_regular_tide",
    "case_prod_quadtree_subgrid_tide",
    "case_prod_riverine",
    "case_prod_storm_amuv",
    "case_prod_compound_snapwave",
)
LENGTHS = ("1h", "6h", "24h", "4d")
LENGTH_SECONDS = {"1h": 3600, "6h": 21600, "24h": 86400, "4d": 345600}

# Default CPU configuration used as the "CPU baseline" in cross-config
# comparisons (the line on wall_vs_length / per_step_vs_length and the
# denominator in gpu_vs_cpu_speedup / gpu_cpu_crossover_heatmap, and the
# CPU column generated by compare.py). Selected as the OpenMP knee on
# the production host per SOR-1025 (the EPYC 7C13's second SMT thread
# per core anti-scales for SFINCS, so cpu_n128 is consistently slower
# than cpu_n64 — see tests/perf/perf-full-20260519/SUMMARY.md). The
# OpenMP scaling plot still spans n1..n128; only the SCALAR CPU
# baseline used in cross-config comparisons changes. Flip this
# constant if a future host has a different SMT geometry.
CPU_REFERENCE = "cpu_n64"

CONFIG_COLORS = {
    CPU_REFERENCE: "#4C72B0",  # blue
    "gpu_n1": "#DD8452",       # orange
    "gpu_n2": "#55A467",       # green
}
CONFIG_LABEL = {CPU_REFERENCE: CPU_REFERENCE, "gpu_n1": "gpu_n1", "gpu_n2": "gpu_n2"}

# Saturation-panel colors — encode the helpful/hurtful direction of
# the rank-count increment. Used by plot_gpu_saturation.
SATURATION_BAR_GREEN = "#2CA02C"  # adding ranks helps (or baseline)
SATURATION_BAR_RED = "#C44E52"    # adding ranks hurts

COMPONENT_COLORS = {
    "boundaries": "#4C72B0",
    "momentum": "#DD8452",
    "continuity": "#55A467",
    "snapwave": "#C44E52",
    "meteo": "#8172B2",
    "output": "#937860",
    "U_L": "#CCB974",
}


